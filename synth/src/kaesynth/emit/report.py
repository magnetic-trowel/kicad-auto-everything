"""BOM CSV and the human-readable build report."""
import csv
import io

from ..checks import summarize


def bom_rows(design):
    groups = {}
    for p in design.all_parts():
        if not p.defn.in_bom:
            continue
        key = (p.defn.mpn or "", p.value or "", p.defn.footprint or "", p.dnp)
        groups.setdefault(key, []).append(p)
    rows = []
    for (mpn, value, fp, dnp), parts in sorted(groups.items(), key=lambda kv: (kv[1][0].defn.prefix, kv[0])):
        defn = parts[0].defn
        rows.append({"Refs": " ".join(sorted((p.ref for p in parts), key=_nat)), "Qty": len(parts),
                     "Value": value, "MPN": mpn or ("generic" if defn.generic else ""),
                     "Manufacturer": defn.manufacturer or "", "Footprint": fp, "Category": defn.category,
                     "Description": defn.description, "Lifecycle": defn.lifecycle or "",
                     "Second source": defn.second_source or "", "Datasheet": defn.datasheet or "",
                     "DNP": "yes" if dnp else ""})
    return rows


def bom_csv(design):
    rows = bom_rows(design)
    buf = io.StringIO()
    if rows:
        w = csv.DictWriter(buf, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return buf.getvalue()


def _nat(s):
    import re
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def _esc(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def report_md(design, findings, kicad, status):
    d = design
    s = summarize(findings)
    L = [f"# {d.title} — build report", "",
         f"Generated by `kaesynth build` from `designs/{d.slug}/design.py`. Do not edit; rebuild instead.", ""]
    L += ["## Status", "",
          "| Gate | Result |", "|---|---|",
          f"| Design checks | {'PASS' if s['error'] == 0 else 'FAIL'} — {s['error']} errors, {s['warning']} warnings, "
          f"{s['waived']} waived |"]
    if kicad.get("ran"):
        L.append(f"| KiCad ERC (kicad-cli {kicad.get('version', '')}) | {kicad['erc_summary']} |")
        L.append(f"| Schematic ↔ IR netlist round trip | {'identical' if not kicad['netlist_problems'] else 'MISMATCH'} |")
        if "dru" in kicad:
            L.append(f"| Custom DRC rules parse | {kicad['dru']} |")
    else:
        L.append(f"| KiCad validation | not run ({kicad.get('reason', '')}) |")
    blocking = [q for q in d.questions if q.blocking and not q.answer]
    L.append(f"| Ready for fabrication | {'NO — ' + str(len(blocking)) + ' blocking questions open' if blocking else ('yes' if status['ok'] else 'no')} |")
    parts = d.all_parts()
    L += ["", f"{len(d.blocks)} blocks, {len(parts)} parts ({len({p.defn.key for p in parts})} distinct), "
          f"{len([n for n in d.all_nets() if n.pins])} nets, {len(d.place.relations)} placement relations.", ""]
    if d.brief:
        L += ["## Brief", "", "> " + d.brief.strip().replace("\n", "\n> "), ""]
    if d.requirements:
        L += ["## Requirements", "", "| ID | Requirement | Value | Source | Verify |", "|---|---|---|---|---|"]
        L += [f"| {r.id} | {_esc(r.text)} | {_esc(r.value)} | {_esc(r.source)} | {_esc(r.verify)} |" for r in d.requirements]
        L.append("")
    if d.questions:
        L += ["## Open questions", "", "| ID | Question | Blocking | Current default | Answer |", "|---|---|---|---|---|"]
        L += [f"| {q.id} | {_esc(q.text)} | {'**yes**' if q.blocking else 'no'} | {_esc(q.default)} | {_esc(q.answer or '—')} |"
              for q in d.questions]
        L.append("")
    if d.assumptions:
        L += ["## Assumptions", ""] + [f"- **{a.id}** {a.text} (confirm: {a.confirm_by})" for a in d.assumptions] + [""]
    if d.hazards:
        L += ["## Hazards", "", "| ID | Hazard | Mitigation | Parts | Single-fault safe |", "|---|---|---|---|---|"]
        for h in d.hazards:
            refs = ", ".join(x.ref if hasattr(x, "ref") else str(x) for x in h.parts) or "procedural"
            L.append(f"| {h.id} | {_esc(h.text)} | {_esc(h.mitigation)} | {refs} | {'yes' if h.single_fault_safe else 'no'} |")
        L.append("")
    if d.domains:
        L += ["## Domains and barriers", "", "| Domain | Kind | 0 V reference | Earthed |", "|---|---|---|---|"]
        L += [f"| {x.name} | {x.kind} | {x.ref} | {'yes' if x.earthed else 'no'} |" for x in d.domains.values()]
        if d.barriers:
            L += ["", "| Between | Grade | Working V | Creepage mm | Clearance mm | Standard | Source |", "|---|---|---|---|---|---|---|"]
            L += [f"| {b.a} / {b.b} | {b.grade} | {b.v_work:g} | {b.creepage_mm:g} | {b.clearance_mm:g} | {_esc(b.standard)} | {_esc(b.source)} |"
                  for b in d.barriers]
        L.append("")
    if d.calcs:
        L += ["## Calculations", "", "| Name | Value | Limit | Expression | Note |", "|---|---|---|---|---|"]
        for c in d.calcs:
            lim = f"{c.op} {c.limit:g}" if c.limit is not None else ""
            L.append(f"| {c.name} | {c.value:.4g} {c.unit} | {lim} | `{_esc(c.expr)}` | {_esc(c.note)} |")
        L.append("")
    L += ["## Findings", ""]
    active = [f for f in findings if not f.waived_by]
    if not active:
        L.append("None.")
    else:
        L += ["| Severity | Check | Message |", "|---|---|---|"]
        order = {"error": 0, "warning": 1, "info": 2}
        L += [f"| {f.severity} | `{f.check}` | {_esc(f.message)} |"
              for f in sorted(active, key=lambda f: (order[f.severity], f.check))]
    waived = [f for f in findings if f.waived_by]
    if waived:
        L += ["", "### Waived", "", "| Check | Message | Waiver |", "|---|---|---|"]
        L += [f"| `{f.check}` | {_esc(f.message)} | {_esc(f.waived_by)} |" for f in waived]
    if kicad.get("ran") and kicad.get("erc_items"):
        L += ["", "### KiCad ERC", "", "| Severity | Type | Description | Items |", "|---|---|---|---|"]
        L += [f"| {v['severity']} | {v['type']} | {_esc(v['description'])} | {_esc('; '.join(v['items'])[:200])} |"
              for v in kicad["erc_items"][:200]]
    if kicad.get("netlist_problems"):
        L += ["", "### Netlist round-trip problems", ""] + [f"- {x}" for x in kicad["netlist_problems"]]
    L += ["", "## Blocks", "", "| Sheet | Title | Parts | Description |", "|---|---|---|---|"]
    L += [f"| {b.name} | {_esc(b.title)} | {len(b.parts)} | {_esc(b.description)} |" for b in d.blocks]
    L.append("")
    return "\n".join(L)
