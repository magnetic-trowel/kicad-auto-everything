"""Build docs/SUBJECTS.md (term -> doc#section) and docs/IDS.md (idea id -> definition).

Terms come from each doc's `Keys:` line (see docs/CONVENTIONS.md). Each term links to the
first section of its doc whose heading or body mentions it, else to the doc itself.
Idea ids come from definition lines `- **XD113** ...`.

    python3 tools/docs/subjects.py          # rewrite both files
    python3 tools/docs/subjects.py --check  # exit 1 if either file is stale
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
OUT_SUBJECTS = DOCS / "SUBJECTS.md"
OUT_IDS = DOCS / "IDS.md"
ID_DEF = re.compile(r"^\s*[-*]\s+\*\*([A-Z]{1,4}\d{1,3}[a-z]?)\*\*\s*(.*)")


def slug(heading: str) -> str:
    """GitHub heading anchor."""
    h = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return h.replace(" ", "-")


def split_keys(line: str) -> list[str]:
    """Split on commas/semicolons that are not inside brackets."""
    out, depth, cur = [], 0, ""
    for ch in line:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth = max(0, depth - 1)
        if ch in ",;" and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [k.strip().strip("`").strip() for k in out if k.strip()]


def sections(text: str):
    """Yield (anchor, heading, body) for each ## or ### section, outside code fences."""
    cur_h, cur_a, body, fence, seen = None, "", [], False, defaultdict(int)
    for line in text.splitlines():
        if line.startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"(#{2,3})\s+(.*)", line)
        if m:
            if cur_h is not None:
                yield cur_a, cur_h, "\n".join(body)
            cur_h = m.group(2)
            a = slug(cur_h)
            cur_a = a if not seen[a] else f"{a}-{seen[a]}"
            seen[a] += 1
            body = []
        else:
            body.append(line)
    if cur_h is not None:
        yield cur_a, cur_h, "\n".join(body)


def rank(term: str, rel: str, text: str) -> float:
    """Higher = more likely the term's canonical home: named in title or filename,
    mentioned often, and a topic or research doc rather than an index."""
    low = text.lower()
    title = low.split("\n", 1)[0]
    stem = Path(rel).stem.replace("-", " ")
    score = min(low.count(term), 20) / 4
    if term in title or term.replace(" ", "-") in rel or term in stem:
        score += 6
    if Path(rel).name == "README.md" or rel.startswith(("ideas/inventory", "digests/")) \
            or rel in ("INDEX.md", "CONVENTIONS.md"):
        score -= 4
    return score


def collect():
    terms = defaultdict(list)  # lower term -> [(display, link)]
    ids = {}
    for p in sorted(DOCS.rglob("*.md")):
        if p in (OUT_SUBJECTS, OUT_IDS):
            continue
        rel = p.relative_to(DOCS).as_posix()
        text = p.read_text(errors="ignore")
        secs = list(sections(text))
        for line in text.splitlines()[:15]:
            if line.startswith("Keys:"):
                for k in split_keys(line[5:]):
                    kl = k.lower()
                    link = rel
                    for a, h, b in secs:
                        if kl in h.lower() or kl in b.lower():
                            link = f"{rel}#{a}"
                            break
                    terms[kl].append((k, link, rank(kl, rel, text)))
                break
        cur_anchor = ""
        for line in text.splitlines():
            m = re.match(r"#{2,3}\s+(.*)", line)
            if m:
                cur_anchor = slug(m.group(1))
            m = ID_DEF.match(line)
            if m and m.group(1) not in ids:
                name = re.split(r"[:(;]", m.group(2), 1)[0].strip()[:70]
                ids[m.group(1)] = (name, f"{rel}#{cur_anchor}" if cur_anchor else rel)
    return terms, ids


def short(link: str) -> str:
    """`topics/physics/lens-cd.md#a-the-passport` -> `physics/lens-cd#a-the-passport`."""
    path, _, frag = link.partition("#")
    path = path.removeprefix("topics/").removesuffix(".md")
    return f"{path}#{frag}" if frag else path


def render(terms, ids):
    s = ["# Subject index", "",
         "Generated by `tools/docs/subjects.py` from each doc's `Keys:` line; do not edit.",
         "Use: `grep -i '<term>' docs/SUBJECTS.md`. The first link is the likeliest main doc. Idea ids (XD113, OP38, ...): [IDS.md](IDS.md).", ""]
    letter = None
    for kl in sorted(terms, key=lambda t: re.sub(r"^\W+", "", t)):
        first = (re.sub(r"^\W+", "", kl)[:1] or "#").upper()
        first = first if first.isalpha() else "#"
        if first != letter:
            letter = first
            s += ["", f"## {letter}", ""]
        entries = sorted(terms[kl], key=lambda e: -e[2])
        links = []
        for _, link, _ in entries:
            if link not in links:
                links.append(link)
        s.append(f"- {entries[0][0]}: " + "; ".join(f"[{short(l)}]({l})" for l in links))
    t = ["# Idea ids", "",
         "Generated by `tools/docs/subjects.py` from definition lines `- **ID** ...`; do not edit.",
         "Use: `grep -w XD113 docs/IDS.md`.", "",
         "| Id | Name | Defined in |", "|---|---|---|"]
    def key(i):
        m = re.match(r"([A-Z]+)(\d+)([a-z]?)", i)
        return (m.group(1), int(m.group(2)), m.group(3))
    for i in sorted(ids, key=key):
        name, link = ids[i]
        t.append(f"| {i} | {name.replace('|', '/')} | [{short(link)}]({link}) |")
    return "\n".join(s) + "\n", "\n".join(t) + "\n"


def main():
    subjects, idtab = render(*collect())
    if "--check" in sys.argv:
        stale = [p.name for p, new in ((OUT_SUBJECTS, subjects), (OUT_IDS, idtab))
                 if not p.exists() or p.read_text() != new]
        if stale:
            print("stale:", ", ".join(stale), "- run tools/docs/subjects.py")
            sys.exit(1)
        return
    OUT_SUBJECTS.write_text(subjects)
    OUT_IDS.write_text(idtab)
    print(f"{OUT_SUBJECTS.relative_to(ROOT)}: {subjects.count(chr(10))} lines; "
          f"{OUT_IDS.relative_to(ROOT)}: {len(idtab.splitlines()) - 7} ids")


if __name__ == "__main__":
    main()
